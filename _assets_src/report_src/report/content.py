def _lines(fname):
    with open(os.path.join(REPO, fname), encoding='utf-8') as f:
        return f.read().split('\n')


def ext(fname, start, end=None, n=None, drop=(), repl=None, after=None):
    """Фрагмент файла: от строки со start до строки с end (включительно) или n строк.
    drop: шаблоны строк, которые выкидываем (на их место ставится строка-многоточие один раз).
    repl: словарь замен (для сокращения слишком длинных значений alt при печати)."""
    L = _lines(fname)
    s0 = 0
    if after:
        s0 = next(i for i, l in enumerate(L) if re.search(after, l))
    i = next(i for i in range(s0, len(L)) if re.search(start, L[i]))
    if end:
        j = next(j for j in range(i, len(L)) if re.search(end, L[j]))
        chunk = L[i:j + 1]
    else:
        chunk = L[i:i + n]
    ind = min(len(l) - len(l.lstrip()) for l in chunk if l.strip())
    out = []
    for l in chunk:
        l = l[ind:]
        if any(re.search(d, l) for d in drop):
            if not out or out[-1].strip() != '...':
                out.append(' ' * (len(l) - len(l.lstrip())) + '...')
            continue
        for a, b in (repl or {}).items():
            l = l.replace(a, b)
        out.append(l)
    # длинные строки тегов переносим по атрибутам
    res = []
    for l in out:
        if len(l) <= 78:
            res.append(l)
            continue
        indent = len(l) - len(l.lstrip())
        parts = re.findall(r'(?:[^\s"]|"[^"]*")+', l.strip())
        cur = ' ' * indent
        first = True
        for p in parts:
            if len(cur) + len(p) + 1 > 78 and cur.strip():
                res.append(cur.rstrip())
                cur = ' ' * (indent + 2)
            cur += p + ' '
        res.append(cur.rstrip())
    return '\n'.join(res)


def git(*args):
    try:
        return subprocess.run(['git', '-C', REPO] + list(args), check=True, capture_output=True,
                              text=True).stdout.strip()
    except Exception:
        return ''


